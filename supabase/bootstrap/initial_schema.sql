create policy "profile: read own or admin" on public.profiles for select
using (id=(select auth.uid()) or (select public.is_admin()));
create policy "profile: update own" on public.profiles for update
using (id=(select auth.uid())) with check (id=(select auth.uid()));
create policy "ledger: read own or admin" on public.credit_ledger for select
using (user_id=(select auth.uid()) or (select public.is_admin()));
create policy "chats: own" on public.chats for all
using (user_id=(select auth.uid())) with check (user_id=(select auth.uid()));
create policy "messages: read own" on public.messages for select
using (user_id=(select auth.uid()));
create policy "packs: public read" on public.credit_packs for select using (active);
create policy "orders: read own or admin" on public.orders for select
using (user_id=(select auth.uid()) or (select public.is_admin()));

